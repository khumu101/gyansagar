class ModelTests(BaseCase):
    def test_slug_autogenerated_and_unique(self):
        lvl = Level.objects.create(name="Class Four", subtitle="Grade 4", icon="4")
        self.assertEqual(lvl.slug, "class-four")
        a = Subject.objects.create(level=self.nursery, name="Maths")
        b = Subject.objects.create(level=self.nursery, name="Maths")
        self.assertEqual(a.slug, "nursery-maths")
        self.assertEqual(b.slug, "nursery-maths-2")
        self.assertEqual(self.cprog.slug, "bsc-csit-c-programming")

    def test_subject_program_must_match_level(self):
        bad = Subject(level=self.nursery, program=self.csit, name="X")
        with self.assertRaises(ValidationError):
            bad.full_clean()

    def test_resource_validation(self):
        with self.assertRaises(ValidationError):  # nothing given
            Resource(subject=self.cprog, kind="notes", title="t").full_clean()
        other = Chapter.objects.create(subject=self.english, order=1, title="A")
        with self.assertRaises(ValidationError):  # chapter of another subject
            Resource(subject=self.cprog, chapter=other, kind="notes", title="t",
                     external_url="https://example.com").full_clean()
        with self.assertRaises(ValidationError):  # live class needs time
            Resource(subject=self.cprog, kind="live-classes", title="t",
                     external_url="https://meet.example.com/x").full_clean()
        Resource(subject=self.cprog, kind="live-classes", title="t", external_url="https://meet.example.com/x",
                 scheduled_at=timezone.now()).full_clean()

    def test_bad_extension_and_scheme_rejected(self):
        r = Resource(subject=self.cprog, kind="notes", title="t",
                     file=SimpleUploadedFile("virus.exe", b"MZ"))
        with self.assertRaises(ValidationError) as cm:
            r.full_clean()
        self.assertIn("file", cm.exception.message_dict)
        with self.assertRaises(ValidationError):
            Resource(subject=self.cprog, kind="notes", title="t", external_url="javascript:alert(1)").full_clean()

    @override_settings(RESOURCE_MAX_UPLOAD_MB=0)
    def test_size_limit(self):
        r = Resource(subject=self.cprog, kind="notes", title="t", file=SimpleUploadedFile("a.pdf", b"x"))
        with self.assertRaises(ValidationError):
            r.full_clean()

    def test_counts_follow_uploads(self):
        n = self.note()
        v = Resource.objects.create(subject=self.cprog, kind="videos", title="Vid", external_url="https://youtu.be/x")
        Resource.objects.create(subject=self.cprog, kind="books", title="Book", external_url="https://example.com/b")
        self.cprog.refresh_from_db()
        self.assertEqual((self.cprog.books_count, self.cprog.videos_count), (2, 1))
        v.is_published = False
        v.save()
        n.delete()
        self.cprog.refresh_from_db()
        self.assertEqual((self.cprog.books_count, self.cprog.videos_count), (1, 0))

    def test_moving_resource_updates_both_subjects(self):
        n = self.note()
        n.subject = self.english
        n.chapter = None
        n.save()
        self.cprog.refresh_from_db(); self.english.refresh_from_db()
        self.assertEqual((self.cprog.books_count, self.english.books_count), (0, 1))

    def test_file_removed_from_disk_on_delete_and_replace(self):
        n = self.note()
        old = n.file.path
        import os
        self.assertTrue(os.path.exists(old))
        n.file = SimpleUploadedFile("new.pdf", b"%PDF new")
        n.save()
        self.assertFalse(os.path.exists(old))
        new = n.file.path
        n.delete()
        self.assertFalse(os.path.exists(new))


