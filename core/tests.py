class SidebarPagesTests(BaseCase):
    def test_every_sidebar_link_resolves(self):
        r = self.client.get(reverse("core:home"))
        links = [l["url"] for l in r.context["sidebar_links"]]
        self.assertEqual(len(links), 20)
        self.assertNotIn("#", links)
        for url in links:
            # AI Tutor needs login -> guests land on the login page (200 after redirect)
            self.assertEqual(self.client.get(url, follow=True).status_code, 200, url)

    def test_home_categories_are_links(self):
        r = self.client.get(reverse("core:home"))
        self.assertTrue(all(c["url"] for c in r.context["categories"]))

    def test_browse_notes_filters_class_faculty_subject(self):
        a = self.note(title="CSIT note")
        b = Resource.objects.create(subject=self.english, kind="notes", title="Nursery note",
                                    external_url="https://example.com/n")
        base = reverse("core:browse", args=["notes"])
        titles = lambda r: {x.title for x in r.context["page_obj"]}
        self.assertEqual(titles(self.client.get(base)), {"CSIT note", "Nursery note"})
        self.assertEqual(titles(self.client.get(base, {"level": "nursery"})), {"Nursery note"})
        self.assertEqual(titles(self.client.get(base, {"level": "bachelor", "program": self.csit.slug})), {"CSIT note"})
        self.assertEqual(titles(self.client.get(base, {"subject": self.cprog.slug})), {"CSIT note"})
        self.assertEqual(titles(self.client.get(base, {"q": "nursery"})), {"Nursery note"})
        r = self.client.get(base, {"level": "bachelor"})
        self.assertIn(self.csit, list(r.context["programs"]))
        r = self.client.get(base, {"program": self.csit.slug})
        self.assertIn(self.cprog, list(r.context["subject_options"]))
        self.assertEqual(r.context["sel_level"], self.bachelor)

    def test_browse_kinds_are_separate_and_unknown_404(self):
        self.note(title="N")
        Resource.objects.create(subject=self.cprog, kind="question-banks", title="Old paper", year=2080,
                                external_url="https://example.com/q")
        r = self.client.get(reverse("core:browse", args=["old-questions"]))
        self.assertEqual({x.title for x in r.context["page_obj"]}, {"Old paper"})
        self.assertEqual(self.client.get("/browse/nonsense/").status_code, 404)

    def test_browse_paginates(self):
        for i in range(25):
            Resource.objects.create(subject=self.cprog, kind="notes", title=f"n{i}", external_url="https://example.com/x")
        r = self.client.get(reverse("core:browse", args=["notes"]))
        self.assertEqual(len(r.context["page_obj"]), 20)
        self.assertEqual(len(self.client.get(reverse("core:browse", args=["notes"]), {"page": 2}).context["page_obj"]), 5)

    def test_courses_and_syllabus_pages(self):
        r = self.client.get(reverse("core:courses"))
        self.assertContains(r, "BSc CSIT")
        r = self.client.get(reverse("core:syllabus"), {"program": self.csit.slug})
        self.assertContains(r, "Pointers")
        r = self.client.get(reverse("core:syllabus"), {"level": "nursery"})
        self.assertContains(r, "English")


