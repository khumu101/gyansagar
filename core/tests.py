        self.assertEqual(r.status_code, 302, getattr(r, "context", None) and r.context["adminform"].form.errors)
        res = Resource.objects.get(title="Pointers note")
        self.assertEqual(res.uploaded_by, self.staff)
        self.cprog.refresh_from_db()
